"""app/engine/coop_deal_engine.py — Step 13: Co-op Deals System.

Co-op deals are structured collaboration opportunities generated by the system.
Players fill predefined roles using their jobs or businesses.  Fixed split
presets distribute payout deterministically — no freeform negotiation.

This is the first true cooperative layer of the Gold Penny economy.  Until
Step 13, all gameplay was player-vs-system.  Co-op deals introduce:
  - Role-based social matching (your job matters to other players)
  - Collective upside (final payout scales with macro economy health)
  - Trust signals (reputation modestly increments on successful collaboration)
  - Contribution scoring (co-op activity feeds the PFT reward engine)

Role-matching rules (deterministic):
  "chef"            — player.main_job == "chef"
  "delivery_driver" — player.main_job == "delivery_driver"
  "auto_mechanic"   — player.main_job == "auto_mechanic"
  "retail_worker"   — player.main_job == "retail_worker"
  "fruit_shop_owner"— player owns an active PlayerBusiness with business_id="fruit_shop"

Payout formula:
  multiplier = clamp(1 + confidence_boost + basket_pressure, 0.80, 1.35)
  confidence_boost = ((consumer_confidence - 50) / 100) × confidence_sensitivity
  basket_pressure  = mean weighted deviation of basket prices from baseline (1.0)
  final_payout     = round(base_payout × multiplier, 2)

Sample lifecycle (Day 18):
  1. Player A (chef) creates "Weekend Festival Food Rush" with split [50, 50].
  2. Player A is auto-assigned to the "chef" role.
  3. Player B (delivery_driver) joins — fills the second role.
  4. Deal transitions to status "filled" automatically.
  5. Complete call is made → final payout calculated from macro state.
  6. XGP split 50 / 50; both players gain +1 reputation.
  7. CoopDealPayout + XGPTransaction rows written for full audit trail.

Unfilled deal example:
  Host creates "Mechanic Rush Contract".  No delivery_driver joins before
  expires_day_number arrives.  expire_open_deals() sets status = "expired".
  Host failed_coop_deals_count increments.  No payout occurs.
"""

